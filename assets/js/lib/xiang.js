  function analyzePalm(opt) {
    var x = SHOU_XING[opt.shape] || SHOU_XING['土'];
    var secs = [];
    var score = 55;
    secs.push({ title: '手形 · ' + x.name, body: x.feat + '。' + x.xing + ' ' + x.ji, basis: x.src });

    var san = ['天纹', '人纹', '地纹'];
    san.forEach(function (k) {
      var v = opt[k];
      if (!v || !LINE_TRAITS[v]) return;
      var tr = LINE_TRAITS[v];
      score += Math.round(tr.d / 2);
      secs.push({
        title: k + '（' + SANCAI[k].alias + '）· ' + v,
        body: SANCAI[k].desc + tr.t,
        basis: '《麻衣相法·掌法》三才纹之说（天纹主情、人纹主智、地纹主命）'
      });
    });

    if (opt.qiu && opt.qiu !== '均平') {
      var q = PALM_QIU[opt.qiu];
      if (q) {
        score += 4;
        secs.push({ title: '掌丘 · ' + opt.qiu, body: q.pos + '，' + q.zhu + '。' + q.up, basis: '相书通说：掌丘以隆起明润为得气' });
      }
    }
    if (opt.se && ZHANG_SE[opt.se]) {
      secs.push({ title: '掌色 · ' + opt.se, body: ZHANG_SE[opt.se], basis: '相书通说：掌色以红润为佳，青暗黄滞为气滞' });
    }
    secs.push({
      title: '总断',
      body: '手为「外五行」之显，掌纹随气血而变，非一成不移。' + x.name + '之人，' + x.xing.replace(/^主/, '其性') +
        '相书有「相由心生、纹随心转」之说，养心节劳则气色自润，纹亦渐明。',
      basis: '《麻衣相法·掌法》；相书通说「相随心转」'
    });
    return { shape: x, sections: secs, score: Math.max(30, Math.min(90, score)), kind: 'palm' };
  }

  function analyzeFace(opt) {
    var secs = [];
    var score = 55;
    if (opt.santing && SANTING[opt.santing]) {
      secs.push({ title: '三停', body: SANTING[opt.santing], basis: '《麻衣相法》三停之说：上停主早年，中停主中年，下停主晚年' });
    }
    ['眉', '眼', '鼻', '口', '耳'].forEach(function (g) {
      var v = opt[g], conf = WU_GUAN[g];
      if (!v || !conf.opts[v]) return;
      secs.push({ title: g + '（' + conf.guan + '）· ' + v, body: conf.opts[v], basis: conf.src });
    });
    if (opt.qise && QI_SE[opt.qise]) {
      score += QI_SE[opt.qise].d;
      secs.push({ title: '气色 · ' + opt.qise, body: QI_SE[opt.qise].t, basis: '《冰鉴·气色》「人以气为主」；相书通说五色应五脏' });
    }
    secs.push({
      title: '总断',
      body: '《冰鉴》论人，先神骨而后气色：「一身精神，具乎两目；一身骨相，具乎面部。」故相面之要，不在美丑而在神气。' +
        '面相之贵，贵在「神藏」「气定」；纵骨相平常，而眼神清澈、气度安详者，亦为可造之器。',
      basis: '《冰鉴·神骨》'
    });
    return { sections: secs, score: Math.max(30, Math.min(90, score)), kind: 'face' };
  }

